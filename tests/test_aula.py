# Testes da Aula guiada (v8.1, R8 do parecer técnico): os três exercícios são resolvidos com comandos
# reais, e a verificação automática precisa reconhecer cada passo certo e explicar cada erro.
# Uso: pip install playwright && playwright install chromium && python tests/test_aula.py
import sys, os
from playwright.sync_api import sync_playwright
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
path=os.path.abspath(sys.argv[1] if len(sys.argv)>1 else os.path.join(ROOT,'index.html')); R=[]
def ok(n,c,i=''):
    R.append((n,bool(c))); print(('PASS ' if c else 'FAIL ')+n+('  '+str(i) if i!='' else ''))
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1400,'height':850})
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e))); pg.on('dialog',lambda d:d.accept())
    pg.goto('file://'+path); pg.wait_for_timeout(500); E=pg.evaluate
    if E("document.getElementById('ov-recover').classList.contains('show')"): E("closeOv('ov-recover')")
    def blur(): E("document.activeElement.blur()")
    def cmd(*seq):
        for t in seq:
            E(f"document.getElementById('cmdinput').value={t!r}"); pg.press('#cmdinput','Enter'); pg.wait_for_timeout(15)
    def st(): return E("(()=>{var s=exState();return {cur:s.cur,ok:s.res.map(r=>r.ok),msg:s.cur>=0?s.res[s.cur].msg:''};})()")
    def verify(): pg.click('#aula-panel .aula-check'); pg.wait_for_timeout(60); return pg.locator('#aula-panel .aula-fb').text_content() if pg.locator('#aula-panel .aula-fb').count() else ''
    # ── abrir pela aba Educacional
    pg.click('#rtab1'); pg.click('#rb-aula'); pg.wait_for_timeout(80)
    ok('Botão Aula guiada (aba Educacional) abre o painel',pg.locator('#aula-panel').is_visible())
    ok('Quatro exercícios disponíveis',E("document.querySelectorAll('#aula-sel option').length")==4)
    E("()=>{addE({tp:'line',x1:0,y1:0,x2:5,y2:5});S.dirty=true;}")
    pg.click('#aula-panel .aula-start'); pg.wait_for_timeout(100)
    ok('Começar: desenho novo e passo 1 em destaque',E("S.ents.length")==0 and st()['cur']==0 and pg.locator('#aula-panel li.cur').count()==1)
    ok('Instrução e botão Dica no passo atual','0,0' in pg.locator('#aula-panel li.cur .aula-ins').text_content())
    pg.click('#aula-panel .aula-hintbtn'); ok('Dica aparece',pg.locator('#aula-panel .aula-hint').is_visible() and 'REC' in pg.locator('#aula-panel .aula-hint').text_content())
    # ── Exercício 1 com erro e correção
    E("()=>{S.modes.snap=false;}")
    cmd('REC','0,0','@120,70')
    fb=verify(); ok('Retângulo com altura errada: diz qual lado falta','falta o lado' in fb and '120,80' in fb,fb)
    E("undo()"); cmd('REC','0,0','@120,80'); pg.wait_for_timeout(400)
    ok('Contorno certo: passo 1 concluído automaticamente',st()['ok'][0] and st()['cur']==1)
    cmd('C','10,10','4'); fb=verify()
    ok('Furos incompletos: aponta o furo que falta','110,10' in fb,fb)
    cmd('C','110,10','4','C','10,70','4','C','110,70','4'); pg.wait_for_timeout(400)
    ok('Quatro furos: passo 2 concluído',st()['ok'][1])
    cmd('DLI','0,0','120,0','60,-12'); pg.wait_for_timeout(300)
    s=st(); ok('Cota antes do estilo ABNT: passo 3 pede o estilo',s['cur']==2 and 'Standard' in s['msg'])
    E("()=>{S.dimCurrent='ABNT';}"); pg.wait_for_timeout(1300)
    s=st(); ok('Estilo ABNT atual: passo 4 explica que a cota 120 usa outro estilo',s['cur']==3 and 'estilo ABNT' in s['msg'],s['msg'])
    E("undo()"); cmd('DLI','0,0','120,0','60,-12','DLI','120,0','120,80','132,40'); pg.wait_for_timeout(300)
    ok('Cotas 120 e 80 em ABNT: passo 4 concluído',st()['ok'][3])
    cmd('DDI','10,10','14,10','25,25'); pg.wait_for_timeout(400)
    ok('Cota Ø8: exercício 1 concluído',st()['cur']==-1 and pg.locator('#aula-panel .aula-done').is_visible())
    ok('Conclusão registrada no navegador',E("!!EXA.done.placa&&EXA.done.placa.best>=0"))
    # ── Exercício 2: vistas
    pg.click('#aula-panel .aula-next'); pg.wait_for_timeout(50); pg.click('#aula-panel .aula-start'); pg.wait_for_timeout(100)
    ok('Próximo exercício: Vistas ortográficas',E("EX_LIST[EXA.cur].id")=='vistas' and st()['cur']==0)
    E("()=>{S.modes.snap=false;S.dimCurrent='ABNT';}")
    cmd('PL','0,0','@60,0','@0,20','@-30,0','@0,20','@-30,0','F'); pg.wait_for_timeout(300)
    ok('Vista frontal por polilinha',st()['ok'][0])
    cmd('REC','5,-20','@60,-30'); s=st()
    ok('Vista superior desalinhada (x de 5 a 65) não é aceita',not s['ok'][1] and 'alinhamento' in s['msg'],s['msg'])
    E("undo()"); cmd('REC','0,-20','@60,-30'); s=st()
    ok('Vista superior sem a aresta do degrau: avisa',not s['ok'][1] and 'x = 30' in s['msg'],s['msg'])
    cmd('L','30,-20','30,-50',''); pg.wait_for_timeout(300)
    ok('Vista superior alinhada e completa',st()['ok'][1])
    cmd('L','80,0','110,0','110,40','80,40','C'); pg.wait_for_timeout(300)
    ok('Vista lateral feita com linhas soltas (não só REC)',st()['ok'][2])
    cmd('L','80,20','110,20',''); s=st()
    ok('Aresta em linha contínua: explica que deve ser tracejada',not s['ok'][3] and 'tracejada' in s['msg'],s['msg'])
    E("()=>{var e=S.ents[S.ents.length-1];snapshot();e.ld='dashed';renderAll();}"); pg.wait_for_timeout(1300)
    ok('Aresta oculta tracejada aceita',st()['ok'][3])
    cmd('DLI','0,0','60,0','30,-8','DLI','0,0','0,40','-10,20','DLI','80,0','110,0','95,-8'); pg.wait_for_timeout(400)
    ok('Cotas 60, 40 e 30: exercício 2 concluído',st()['cur']==-1)
    # ── Exercício 3: horta
    E("exSelect(2)"); pg.click('#aula-panel .aula-start'); pg.wait_for_timeout(100)
    E("()=>{S.modes.snap=false;S.dimCurrent='ABNT';}")
    ok('Exercício 3 começa pedindo a camada Terreno','Terreno' in st()['msg'])
    E("()=>{S.layers.push({id:50,nm:'Terreno',col:'#88cc88',vis:true,lock:false,ld:'solid',lw:.5});updLayerUI();}"); pg.wait_for_timeout(1300)
    ok('Camada Terreno criada',st()['ok'][0])
    cmd('REC','0,0','@8000,6000'); s=st()
    ok('Terreno na camada errada: explica',not s['ok'][1] and 'camada Terreno' in s['msg'],s['msg'])
    E("()=>{snapshot();S.ents[S.ents.length-1].ly=50;renderAll();}"); pg.wait_for_timeout(1300)
    ok('Terreno na camada Terreno',st()['ok'][1])
    cmd('REC','700,500','@1200,5000'); pg.wait_for_timeout(300)
    ok('Primeiro canteiro',st()['ok'][2])
    E("()=>{S.sel=[S.ents[S.ents.length-1].id];}"); cmd('CO','700,500','M','4','@1800,0',''); pg.wait_for_timeout(300)
    ok('Mais três canteiros com COPY Matriz',st()['ok'][3],st()['msg'])
    E("()=>{setTool('hatch');[0,1,2].forEach(i=>handleClick({x:700+1800*i+600,y:3000}));}"); cmd(''); s=st()
    ok('Três canteiros hachurados: aponta o 4º',not s['ok'][4] and 'canteiro 4' in s['msg'],s['msg'])
    E("()=>{setTool('hatch');handleClick({x:6100+600,y:3000});}"); cmd(''); pg.wait_for_timeout(300)
    ok('Os quatro canteiros hachurados',st()['ok'][4])
    cmd('DLI','700,500','1900,500','1300,-300','DCO','2500,500','','DLI','0,0','8000,0','4000,-1000'); pg.wait_for_timeout(400)
    ok('Cotas 1200, 600 (em série) e 8000',st()['ok'][5],st()['msg'])
    E("()=>{switchSpace('layout');var v=curViewport();v.k=unitMm()/100;renderAll();}"); pg.wait_for_timeout(200); s=st()
    ok('Layout aberto: pede a escala 1:50',not s['ok'][6] and '1:50' in s['msg'],s['msg'])
    pg.select_option('#lc-scale',str(1/50)); E("titleBlockInsert()"); pg.wait_for_timeout(1300); s=st()
    ok('Carimbo inserido: pede o título preenchido','título' in s['msg'],s['msg'])
    E("()=>{var t=S.ents.find(e=>e.tp==='mtext'&&e.txt==='TÍTULO DO DESENHO');snapshot();t.txt='PLANTA DA HORTA';renderAll();}"); pg.wait_for_timeout(1300)
    ok('Prancha 1:50 com carimbo: exercício 3 concluído',st()['cur']==-1 and pg.locator('#aula-panel .aula-done').is_visible())
    # ── comando e fechamento
    pg.click('#aula-panel .aula-x'); ok('Fechar o painel',not pg.locator('#aula-panel').is_visible())
    E("document.getElementById('cmdinput').value='AULA'"); pg.press('#cmdinput','Enter'); pg.wait_for_timeout(60)
    ok('Comando AULA abre o painel',pg.locator('#aula-panel').is_visible())
    ok('Exercícios concluídos marcados com ✓',E("Array.from(document.querySelectorAll('#aula-sel option')).filter(o=>o.textContent.indexOf('✓')>=0).length")>=0)
    ok('Sem erros JavaScript',not errs,errs)
    b.close()
fails=[n for n,c in R if not c]; print(f'\n{len(R)-len(fails)}/{len(R)} testes OK'); sys.exit(1 if fails else 0)
