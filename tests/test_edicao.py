# Testes de edição e precisão (v6.4): ByLayer, propriedades, geometria, OSNAP e grips.
# Uso: pip install playwright ezdxf && playwright install chromium && python tests/test_edicao.py
import sys, os, math, io
from playwright.sync_api import sync_playwright
HERE=os.path.dirname(os.path.abspath(__file__))
path=os.path.abspath(sys.argv[1] if len(sys.argv)>1 else os.path.join(HERE,'..','index.html')); R=[]
def ok(n,c,i=''):
    R.append((n,bool(c))); print(('PASS ' if c else 'FAIL ')+n+('  '+str(i) if i!='' else ''))
def near(a,b,t=1e-6): return abs(a-b)<t
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1400,'height':850})
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e))); pg.on('dialog',lambda d:d.accept())
    pg.goto('file://'+path); pg.wait_for_timeout(400); E=pg.evaluate
    box=pg.locator('#cw').bounding_box()
    def scr(x,y):
        s=E(f"w2s({x},{y})"); return box['x']+s['x'], box['y']+s['y']
    def reset():
        E("()=>{S.ents=[];S.sel=[];S.grip=null;S.ds=null;resetHistory();setTool('select');S.vp={x:Math.round(S.cD.width/2),y:Math.round(S.cD.height/2),sc:4};S.style={col:null,lw:null,ld:null};S.modes.tan=false;S.modes.nea=false;S.modes.osnap=true;renderAll();updSelInfo();}")
    def click(x,y): pg.mouse.move(*scr(x,y)); pg.mouse.click(*scr(x,y)); pg.wait_for_timeout(30)
    def blur(): E("document.activeElement.blur()")
    # ── ByLayer
    reset()
    r=E("()=>{setTool('line');handleClick({x:0,y:0});handleClick({x:20,y:0});cancelTool();var e=S.ents[0];return [e.col,e.lw,e.ld,effCol(e)];}")
    ok('Novos objetos são ByLayer por padrão',r[0] is None and r[1] is None and r[2] is None and r[3]=='#dce4f5',r)
    r=E("()=>{getLy(0).col='#ff0000';return effCol(S.ents[0]);}"); E("()=>{getLy(0).col='#dce4f5'}")
    ok('Objeto ByLayer acompanha a cor da camada',r=='#ff0000')
    ok('Painel sem seleção edita os novos objetos',E("document.getElementById('prop-hdr').textContent").endswith('novos objetos') and E("document.getElementById('propColMode').value")=='')
    # ── Propriedades da seleção
    reset()
    E("()=>{addE({tp:'line',x1:0,y1:0,x2:20,y2:0,col:'#ff0000'});addE({tp:'circ',cx:40,cy:0,r:5,col:'#00ff00'});S.sel=S.ents.map(e=>e.id);updSelInfo();}")
    ok('Cores diferentes mostram *VARIA*',E("document.getElementById('propColMode').value")=='__varies__' and '2 selecionados' in E("document.getElementById('prop-hdr').textContent"))
    pg.select_option('#propColMode',''); pg.wait_for_timeout(50)
    ok('ByLayer aplicado à seleção',E("S.ents.every(e=>e.col===null)"))
    E("()=>{var s=document.getElementById('propLW');s.value='.35';s.dispatchEvent(new Event('change'));}")
    pg.select_option('#propLy','1'); pg.wait_for_timeout(50)
    ok('Espessura e camada aplicadas à seleção',E("S.ents.every(e=>e.lw===.35&&e.ly===1)"))
    E("undo()")
    ok('Alteração de propriedade pode ser desfeita',E("S.ents.every(e=>e.ly===0)"))
    ok('Estilo dos novos objetos não é afetado pela edição da seleção',E("S.style.lw===null&&S.curLy===0"))
    # ── Geometria editável
    reset(); E("()=>{addE({tp:'line',x1:0,y1:0,x2:30,y2:40});S.sel=[S.ents[0].id];updSelInfo();}")
    rows=E("Array.from(document.querySelectorAll('#selinfo .geo-row')).map(r=>r.children[0].textContent)")
    ok('Painel mostra geometria da linha',rows[:6]==['Início X','Início Y','Fim X','Fim Y','Comprimento','Ângulo (°)'],rows)
    inp=pg.locator('#selinfo .geo-row').nth(4).locator('input'); inp.fill('100'); inp.press('Enter'); pg.wait_for_timeout(50)
    r=E("[S.ents[0].x2,S.ents[0].y2]")
    ok('Editar comprimento mantém o ângulo',near(r[0],60) and near(r[1],80),r)
    E("()=>{S.ents=[];addE({tp:'circ',cx:0,cy:0,r:5});S.sel=[S.ents[0].id];updSelInfo();}")
    inp=pg.locator('#selinfo .geo-row').nth(3).locator('input'); inp.fill('-4'); inp.press('Enter')
    ok('Valor inválido é recusado e sinalizado',E("S.ents[0].r")==5 and 'bad' in inp.get_attribute('class'))
    inp.fill('30'); inp.press('Enter')
    ok('Diâmetro editado',near(E("S.ents[0].r"),15))
    # ── OSNAP
    reset(); E("()=>{addE({tp:'circ',cx:0,cy:0,r:10});addE({tp:'line',x1:-50,y1:-30,x2:50,y2:-30});}")
    def snapAt(x,y): return E(f"(()=>{{var s=w2s({x},{y});return doSnap(s.x,s.y);}})()")
    r=snapAt(10.6,0.4); ok('OSNAP quadrante',r['st']=='quad' and near(r['x'],10) and near(r['y'],0),r)
    E("()=>{setTool('line');handleClick({x:20,y:-10});}")
    r=snapAt(20.4,-29.6); ok('OSNAP perpendicular',r['st']=='per' and near(r['x'],20) and near(r['y'],-30),r)
    E("()=>{cancelTool();setTool('line');handleClick({x:30,y:0});S.modes.tan=true;}")
    tx,ty=10/3,math.sqrt(100-(10/3)**2)
    r=snapAt(tx+0.3,ty+0.3); ok('OSNAP tangente',r['st']=='tan' and near(r['x'],tx) and near(r['y'],ty),r)
    E("()=>{cancelTool();S.modes.tan=false;S.modes.nea=true;}")
    r=snapAt(31.3,-29.2); ok('OSNAP próximo (projeção exata)',r['st']=='nea' and near(r['x'],31.3) and near(r['y'],-30),r)
    r=snapAt(50.5,-29.6); ok('Próximo tem prioridade menor que extremidade',r['st']=='end',r)
    E("()=>{S.modes.nea=false;setTool('line');handleClick({x:20,y:-10});}")
    pg.click('#cmdinput'); pg.keyboard.type('NEA'); pg.keyboard.press('Enter')
    r=snapAt(30.7,-29.4); ok('Substituição NEA pela linha de comando',r['st']=='nea' and E("S.snapOverride")=='nea',r)
    E("()=>{cancelTool();S.snapOverride=null;}")
    blur(); pg.keyboard.press('F3')
    r=snapAt(10.6,0.4); ok('F3 desliga os snaps de objeto',r['st'] in (None,'grid') and E("S.modes.osnap")==False,r)
    pg.keyboard.press('F3')
    # ── GRIPS
    reset(); E("()=>{addE({tp:'line',x1:0,y1:0,x2:40,y2:0});S.sel=[S.ents[0].id];renderAll();}")
    click(40,0); ok('Clique no grip entra em STRETCH',E("S.grip&&S.grip.mode")=='stretch')
    click(40,30); r=E("[S.ents[0].x2,S.ents[0].y2,S.ents[0].x1]")
    ok('STRETCH move a extremidade',near(r[0],40) and near(r[1],30) and near(r[2],0),r)
    E("undo()"); ok('Grip desfeito em um passo',near(E("S.ents[0].y2"),0))
    reset(); E("()=>{addE({tp:'line',x1:0,y1:0,x2:20,y2:0});addE({tp:'line',x1:20,y1:0,x2:20,y2:20});S.sel=S.ents.map(e=>e.id);renderAll();}")
    click(20,0); click(25,-5)
    ok('Grips coincidentes movem as duas linhas',E("[S.ents[0].x2,S.ents[0].y2,S.ents[1].x1,S.ents[1].y1]")==[25,-5,25,-5])
    reset(); E("()=>{addE({tp:'rect',x:0,y:0,w:20,h:10});S.sel=[S.ents[0].id];renderAll();}")
    click(20,10); click(30,15); r=E("[S.ents[0].x,S.ents[0].y,S.ents[0].w,S.ents[0].h]")
    ok('Canto do retângulo redimensiona mantendo o oposto',r==[0,0,30,15],r)
    reset(); E("()=>{addE({tp:'line',x1:0,y1:0,x2:20,y2:0});S.sel=[S.ents[0].id];renderAll();}")
    click(0,0); blur(); pg.keyboard.press(' ')
    ok('Espaço alterna para MOVE',E("S.grip.mode")=='move')
    click(10,10); r=E("[S.ents[0].x1,S.ents[0].y1,S.ents[0].x2]"); ok('MOVE desloca o objeto',near(r[0],10) and near(r[1],10) and near(r[2],30),r)
    click(10,10); blur(); pg.keyboard.press(' '); pg.keyboard.press(' ')
    pg.click('#cmdinput'); pg.keyboard.type('90'); pg.keyboard.press('Enter')
    r=E("[S.ents[0].x2,S.ents[0].y2]"); ok('ROTATE com ângulo digitado',near(r[0],10) and near(r[1],30),r)
    blur(); click(10,10)
    for _ in range(3): pg.keyboard.press(' ')
    ok('Ciclo chega a SCALE',E("S.grip.mode")=='scale')
    pg.click('#cmdinput'); pg.keyboard.type('0,5'); pg.keyboard.press('Enter')
    r=E("[S.ents[0].x2,S.ents[0].y2]"); ok('SCALE com fator digitado (vírgula decimal)',near(r[0],10) and near(r[1],20),r)
    blur(); click(10,10); pg.keyboard.press(' ')
    pg.click('#cmdinput'); pg.keyboard.type('C'); pg.keyboard.press('Enter')
    blur(); click(50,10); click(90,10)
    ok('Opção Copiar cria cópias e mantém o original',E("S.ents.length")==3 and near(E("S.ents[0].x1"),10) and E("!!S.grip"),E("[S.ents.length,S.ents[0].x1,!!S.grip]"))
    pg.keyboard.press('Escape'); ok('Esc encerra o grip e mantém a seleção',E("!S.grip&&S.sel.length===1"))
    pg.keyboard.press('Escape'); ok('Segundo Esc limpa a seleção',E("S.sel.length")==0)
    reset(); E("()=>{addE({tp:'circ',cx:0,cy:0,r:10});S.sel=[S.ents[0].id];renderAll();}")
    pg.mouse.move(*scr(10,0)); pg.mouse.down(); pg.mouse.move(*scr(15,0),steps=5); pg.mouse.move(*scr(20,0),steps=5); pg.mouse.up(); pg.wait_for_timeout(30)
    ok('Arrastar o grip do quadrante muda o raio',near(E("S.ents[0].r"),20) and not E("!!S.grip"))
    reset(); E("()=>{addE({tp:'pl',closed:true,pts:[{x:0,y:0},{x:20,y:0},{x:20,y:20},{x:0,y:20},{x:0,y:0}]});S.sel=[S.ents[0].id];renderAll();}")
    click(0,0); click(-5,-5); r=E("S.ents[0].pts")
    ok('Vértice inicial de polilinha fechada move o ponto duplicado junto',all(near(r[i][k],-5) for i in (0,4) for k in 'xy'),r[0])
    click(10,20); click(10,30); r=E("S.ents[0].pts")
    ok('Grip de meio de segmento estira o segmento',near(r[2]['x'],20) and near(r[2]['y'],30) and near(r[3]['x'],0) and near(r[3]['y'],30),r)
    E("()=>{S.modes.grips=false;}"); ok('GRIPS desligado não mostra alças',E("allGrips().length")==0); E("()=>{S.modes.grips=true;}")
    reset(); E("()=>{for(var i=0;i<120;i++)addE({tp:'line',x1:i,y1:0,x2:i,y2:5},true);S.sel=S.ents.map(e=>e.id);}")
    ok('Mais de 100 objetos selecionados: sem grips (desempenho)',E("allGrips().length")==0)
    # ── DXF ByLayer
    reset(); E("()=>{addE({tp:'line',x1:0,y1:0,x2:10,y2:0});addE({tp:'line',x1:0,y1:5,x2:10,y2:5,col:'#ff0000',lw:.5,ld:'solid'});}")
    import ezdxf
    _f=os.path.join(HERE,'_bylayer.dxf'); open(_f,'wb').write(bytes(E("Array.from(cp1252Encode(buildDXF2000({})))")))
    d=ezdxf.readfile(_f); os.remove(_f)
    L=list(d.modelspace().query('LINE'))
    ok('DXF: ByLayer sai como ByLayer; explícito mantém cor, espessura e tipo',L[0].dxf.color==256 and L[0].dxf.lineweight==-1 and L[0].dxf.linetype=='BYLAYER' and L[1].rgb==(255,0,0) and L[1].dxf.lineweight==50 and L[1].dxf.linetype=='Continuous')
    ok('Sem erros JavaScript',not errs,errs)
    b.close()
f=[n for n,c in R if not c]; print(f'\n{len(R)-len(f)}/{len(R)} testes OK'); sys.exit(1 if f else 0)
