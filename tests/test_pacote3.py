# Testes do pacote 3 da v7 (v7.2): hachura por contorno, MTEXT, LEADER, BLOCK/INSERT,
# seleção cruzando pela geometria real e importação de DXF (arquivos gerados pelo ezdxf).
# Uso: pip install playwright ezdxf && playwright install chromium && python tests/test_pacote3.py
import sys, os, math, json
from playwright.sync_api import sync_playwright
import ezdxf
HERE=os.path.dirname(os.path.abspath(__file__))
path=os.path.abspath(sys.argv[1] if len(sys.argv)>1 else os.path.join(HERE,'..','index.html')); R=[]
def ok(n,c,i=''):
    R.append((n,bool(c))); print(('PASS ' if c else 'FAIL ')+n+('  '+str(i) if i!='' else ''))
def near(a,b,t=1e-6): return abs(a-b)<t
TMP=lambda f: os.path.join(HERE,'_'+f)
# ── arquivos DXF de teste (ezdxf)
d=ezdxf.new('R2000'); d.header['$INSUNITS']=4; msp=d.modelspace()
d.layers.add('Paredes',color=1); d.layers.add('Textos',color=3,linetype='DASHED')
msp.add_line((0,0),(100,0),dxfattribs={'layer':'Paredes'})
msp.add_circle((50,50),10,dxfattribs={'color':5}); msp.add_arc((0,0),20,0,90)
msp.add_lwpolyline([(0,0,0,0,0.41421356),(20,0,0,0,0),(40,20)],format='xyseb')
msp.add_text('Olá',dxfattribs={'height':5,'insert':(10,10),'layer':'Textos'})
msp.add_mtext('Linha 1\\PLinha 2',dxfattribs={'char_height':3,'insert':(0,60)})
msp.add_ellipse((80,80),major_axis=(20,0),ratio=0.5)
msp.add_spline([(0,100),(10,110),(20,100),(30,110)])
b=d.blocks.new('MESA'); b.add_line((0,0),(10,0)); b.add_line((10,0),(10,5))
msp.add_blockref('MESA',(200,0),dxfattribs={'xscale':2,'yscale':2,'rotation':90})
h=msp.add_hatch(); h.set_pattern_fill('ANSI31',scale=1); h.paths.add_polyline_path([(300,0),(320,0),(320,20),(300,20)],is_closed=True)
dm=msp.add_linear_dim(base=(0,-20),p1=(0,0),p2=(100,0)); dm.render()
d.saveas(TMP('a.dxf'))
di=ezdxf.new('R2000'); di.header['$INSUNITS']=1; di.modelspace().add_line((0,0),(1,0)); di.saveas(TMP('in.dxf'))
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1400,'height':850},accept_downloads=True)
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e))); pg.on('dialog',lambda d_:d_.accept())
    pg.goto('file://'+path); pg.wait_for_timeout(400); E=pg.evaluate
    box=pg.locator('#cw').bounding_box()
    def scr(x,y):
        s=E(f"w2s({x},{y})"); return box['x']+s['x'], box['y']+s['y']
    def click(x,y): pg.mouse.move(*scr(x,y)); pg.mouse.click(*scr(x,y)); pg.wait_for_timeout(30)
    def blur(): E("document.activeElement.blur()")
    def typ(t): blur(); pg.keyboard.type(t); pg.keyboard.press('Enter'); pg.wait_for_timeout(30)
    def reset():
        E("()=>{S.ents=[];S.sel=[];S.grip=null;S.ds=null;S.blocks={};resetHistory();setTool('select');S.modes.snap=false;S.vp={x:Math.round(S.cD.width/2)-200,y:Math.round(S.cD.height/2)+150,sc:4};renderAll();}")
    def L(): return E("S.ents.map(e=>JSON.parse(JSON.stringify(e)))")
    def lines(seq):
        for q in seq: E(f"addE({{tp:'line',x1:{q[0]},y1:{q[1]},x2:{q[2]},y2:{q[3]}}})")
    # ── HACHURA por ponto interno
    reset(); lines([(0,0,40,0),(40,0,40,15),(40,15,0,15),(0,15,0,0)])
    typ('H'); ok('H inicia a hachura por ponto interno',E("S.ds&&S.ds.phase")=='pick')
    click(20,7); typ('')
    e=[x for x in L() if x['tp']=='hatch']
    ok('Contorno formado por 4 linhas separadas é encontrado',len(e)==1 and len(e[0]['loops'])==1 and near(abs(E("polyArea(S.ents.find(e=>e.tp==='hatch').loops[0])")),600),e[0]['loops'] if e else e)
    reset(); E("()=>{addE({tp:'rect',x:0,y:0,w:60,h:40});addE({tp:'circ',cx:30,cy:20,r:8});}")
    typ('H'); click(5,5); typ('')
    e=[x for x in L() if x['tp']=='hatch']
    ok('Círculo interno vira ilha',len(e)==1 and len(e[0]['loops'])==2)
    ok('Ponto dentro da ilha não é hachurado',not E("hitEnt(S.ents.find(e=>e.tp==='hatch'),30,20)") and E("hitEnt(S.ents.find(e=>e.tp==='hatch'),5,5)"))
    ar=E("geomFields(S.ents.find(e=>e.tp==='hatch')).find(f=>f.l==='Área').v")
    ok('Área descontando a ilha',abs(ar-(2400-math.pi*64))<1.5,ar)
    reset(); lines([(0,0,40,0),(40,0,40,15),(40,15,0,15),(0,15,0,0),(20,0,20,15)])
    typ('H'); click(10,7); typ('')
    hb=E("bbox(S.ents.find(e=>e.tp==='hatch'))")
    ok('Região dividida: hachura só a metade clicada',near(hb['w'],20) and near(hb['x'],0),hb)
    reset(); lines([(0,0,40,0),(40,0,40,15),(40,15,0,15)])
    typ('H'); click(20,7); typ('')
    ok('Contorno aberto: avisa e não cria hachura',not any(x['tp']=='hatch' for x in L()))
    reset(); E("()=>{addE({tp:'rect',x:0,y:0,w:60,h:40});addE({tp:'circ',cx:30,cy:20,r:8});}")
    typ('H'); click(5,5); typ('')
    E("()=>{var h=S.ents.find(e=>e.tp==='hatch');transl(h,100,0);}")
    ok('Hachura acompanha MOVE',near(E("bbox(S.ents.find(e=>e.tp==='hatch')).x"),100))
    _f=TMP('h.dxf'); open(_f,'wb').write(bytes(E("Array.from(cp1252Encode(buildDXF2000({})))")))
    hh=ezdxf.readfile(_f).modelspace().query('HATCH')[0]
    ok('DXF: HATCH com contorno e ilha (2 caminhos)',len(hh.paths)==2)
    # ── MTEXT
    reset(); typ('T'); ok('T inicia MTEXT (como no AutoCAD)',E("S.tool")=='mtext')
    click(0,40); click(25,20)
    ok('Editor de texto abre após os dois cantos',E("document.getElementById('ov-mtext').classList.contains('show')"))
    pg.fill('#mted-txt',''); pg.click('#mted-txt'); pg.keyboard.type('Canteiro A'); pg.keyboard.press('Enter'); pg.keyboard.type('Área de cultivo de hortaliças')
    pg.keyboard.press('Control+Enter'); pg.wait_for_timeout(50)
    e=L(); ok('MTEXT criado com quebra de linha',len(e)==1 and e[0]['tp']=='mtext' and e[0]['txt'].split('\n')==['Canteiro A','Área de cultivo de hortaliças'],e)
    nl=E("mtLines(S.ents[0]).length"); ok('Texto longo quebra pela largura do quadro',nl>=3,nl)
    bb=E("bbox(S.ents[0])"); ok('MTEXT começa no canto superior esquerdo',near(bb['x'],0,1e-6) and bb['y']+bb['h']<=40+1e-6,bb)
    pg.mouse.dblclick(*scr(2,37)); pg.wait_for_timeout(50)
    ok('Duplo clique abre o editor',E("document.getElementById('ov-mtext').classList.contains('show')"))
    pg.fill('#mted-txt','Canteiro B'); pg.click("#ov-mtext .btn.p"); pg.wait_for_timeout(30)
    ok('Texto editado',L()[0]['txt']=='Canteiro B')
    _f=TMP('m.dxf'); open(_f,'wb').write(bytes(E("Array.from(cp1252Encode(buildDXF2000({})))")))
    ok('DXF: MTEXT nativo',len(ezdxf.readfile(_f).modelspace().query('MTEXT'))==1)
    # ── LEADER
    reset(); typ('LE'); click(0,0); click(15,15); typ('')
    ok('LEADER abre o editor após Enter',E("document.getElementById('ov-mtext').classList.contains('show')"))
    pg.fill('#mted-txt','Dreno'); pg.click("#ov-mtext .btn.p"); pg.wait_for_timeout(30)
    e=L(); ok('Linha de chamada criada com texto',len(e)==1 and e[0]['tp']=='leader' and e[0]['txt']=='Dreno')
    pr=E("leaderPrims(S.ents[0]).map(p=>p.k)"); ok('Leader tem seta, linhas e texto',('solid' in pr) and ('text' in pr) and pr.count('line')>=2,pr)
    # ── BLOCK / INSERT
    reset(); lines([(0,0,10,0),(10,0,10,5)])
    typ('B'); typ('Mesa'); click(0,0); click(-2,-2); click(12,7); typ(''); typ('')
    e=L(); ok('BLOCK define e converte a seleção em referência',len(e)==1 and e[0]['tp']=='insert' and 'Mesa' in E("Object.keys(S.blocks)"),e)
    typ('I'); typ('Mesa'); click(50,0); typ('2'); typ('90')
    e=L(); bb=E("bbox(S.ents[1])")
    ok('INSERT com escala 2 e rotação 90°',e[1]['tp']=='insert' and near(bb['w'],10) and near(bb['h'],20) and near(bb['x'],40),bb)
    ok('Clique seleciona a referência de bloco',E("hitEnt(S.ents[1],50,10)"))
    E("()=>{S.sel=[S.ents[1].id];}"); typ('X')
    ok('EXPLODE da referência gera as linhas do bloco',[x['tp'] for x in L()]==['insert','line','line'])
    E("mirr(S.ents[0],{x:-5,y:-100},{x:-5,y:100})"); bb=E("bbox(S.ents[0])")
    ok('MIRROR de bloco',near(bb['x'],-20) and near(bb['w'],10),bb)
    doc=E("JSON.stringify({ents:S.ents,layers:S.layers,blocks:S.blocks})"); open(TMP('b.json'),'w').write(doc)
    E("()=>{S.blocks={};S.ents=[];}"); pg.set_input_files('#fileInput',TMP('b.json')); pg.wait_for_timeout(200)
    ok('Blocos salvos e restaurados no JSON','Mesa' in E("Object.keys(S.blocks)") and E("S.ents.filter(e=>e.tp==='insert').length")==1)
    _f=TMP('bl.dxf'); open(_f,'wb').write(bytes(E("Array.from(cp1252Encode(buildDXF2000({})))")))
    _d=ezdxf.readfile(_f); _I=_d.modelspace().query('INSERT')
    ok('DXF: referência de bloco exportada como INSERT, com a geometria na definição (v8.6)',len(_I)==1 and len(_d.blocks.get(_I[0].dxf.name).query('LINE'))==2)
    open(_f,'wb').write(bytes(E("Array.from(cp1252Encode(buildDXF2000({blocks:'exploded'})))")))
    ok('DXF: opção de blocos explodidos em geometria',len(ezdxf.readfile(_f).modelspace().query('LINE'))>=4)
    # ── seleção cruzando pela geometria real
    reset(); E("addE({tp:'line',x1:0,y1:0,x2:40,y2:40})")
    typ('M'); click(35,5); click(25,12)
    ok('Cruzando não pega linha diagonal que só passa perto (bbox)',E("S.ds.ids.length")==0)
    click(30,25); click(15,15)
    ok('Cruzando pega quando a linha atravessa a janela',E("S.ds.ids.length")==1)
    pg.keyboard.press('Escape')
    # ── importação de DXF
    reset(); pg.set_input_files('#fileInput',TMP('a.dxf')); pg.wait_for_timeout(500)
    tps=E("S.ents.map(e=>e.tp)")
    ok('DXF importado: tipos principais',all(t in tps for t in ['line','circ','arc','pl','txt','mtext','ell','spline','insert','hatch']),sorted(set(tps)))
    ok('Camadas com nome e cor',E("(S.layers.find(l=>l.nm==='Paredes')||{}).col")=='#ff0000' and E("(S.layers.find(l=>l.nm==='Textos')||{}).ld")=='dashed')
    ok('Polilinha com bulge preservado',E("S.ents.some(e=>e.tp==='pl'&&e.pts.some(p=>Math.abs((p.b||0)-0.41421356)<1e-6))"))
    ok('MTEXT com quebra de linha (\\P)',E("S.ents.find(e=>e.tp==='mtext').txt")=='Linha 1\nLinha 2')
    ok('Texto com acento (UTF-8/1252)',E("S.ents.find(e=>e.tp==='txt').txt")=='Olá')
    ok('Bloco importado e referenciado','MESA' in E("Object.keys(S.blocks)"))
    ok('Cota importada como geometria (texto 100)',E("S.ents.some(e=>(e.tp==='txt'||e.tp==='mtext')&&/100/.test(e.txt))"))
    ok('Título passa a ser o nome do arquivo',E("document.getElementById('ftitle').textContent").endswith('a.dxf'))
    reset(); pg.set_input_files('#fileInput',TMP('in.dxf')); pg.wait_for_timeout(300)
    ok('Unidades em polegadas convertidas para mm',near(E("S.ents[0].x2"),25.4))
    # ── ida e volta
    reset(); E("()=>{addE({tp:'rect',x:0,y:0,w:30,h:20});addE({tp:'circ',cx:15,cy:10,r:4});addE({tp:'pl',closed:false,pts:[{x:0,y:30},{x:20,y:30,b:0.5},{x:40,y:40}]});addE({tp:'mtext',x:0,y:60,w:0,h:3,txt:'A\\nB',att:1,rot:0});}")
    buf=E("Array.from(cp1252Encode(buildDXF2000({})))")
    E(f"()=>{{importDxfBuffer(new Uint8Array({json.dumps(buf)}).buffer,'ida-volta.dxf',false);}}")
    tps=sorted(E("S.ents.map(e=>e.tp)"))
    ok('Ida e volta: exportar DXF 2000 e reabrir',tps==['circ','mtext','pl','pl'] and E("S.ents.find(e=>e.tp==='mtext').txt")=='A\nB',tps)
    ok('Sem erros JavaScript',not errs,errs)
    b.close()
for fn in os.listdir(HERE):
    if fn.startswith('_'): os.remove(os.path.join(HERE,fn))
f=[n for n,c in R if not c]; print(f'\n{len(R)-len(f)}/{len(R)} testes OK'); sys.exit(1 if f else 0)
