    reset(); E("()=>scrRun('RECTANG 0,0 10,10\\nRECTANG 20,0 30,10\\nRECTANG 40,0 50,10\\nRECTANG 60,0 70,10\\n',{delay:200})"); pg.wait_for_timeout(250)
