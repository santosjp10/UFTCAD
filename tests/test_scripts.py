    ok('Cota linear por três pontos digitados',tps()==['rect','dim'],e[-1:])
    # ── comandos digitados continuam como antes (TEXT/POL com janela)
    reset(); E("cmdSubmit('POL')"); ok('POL digitado continua abrindo a janela',E("document.getElementById('ov-polygon').classList.contains('show')")); E("closeOv('ov-polygon')")
    reset(); E("cmdSubmit('-LAYER')"); E("cmdSubmit('M')"); E("cmdSubmit('Digitada')"); E("cmdSubmit('')")
    ok('-LAYER também pode ser digitado',E("getLy(S.curLy).nm")=='Digitada')
