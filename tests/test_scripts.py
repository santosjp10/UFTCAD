    run('ZOOM 2X\n'); ok('ZOOM com fator',E("S.vp.sc")>2)
    reset(); E("()=>{if(S.modes.osnap)toggleMode('osnap');}"); run('OSMODE 1\nORTHOMODE 1\n')
    ok('Variáveis OSMODE e ORTHOMODE',E("[S.modes.osnap,S.modes.ortho]")==[True,True]); run('ORTHOMODE 0\n')
