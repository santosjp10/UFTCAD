    ok('HPNAME/HPSCALE/HPANG + HATCH por ponto interno',len(h)==1 and h[0].get('pname')=='GRASS' and near(h[0]['sp'],25.4*2) and near(h[0]['ang'],15),h)
    reset(); run('HPNAME CULTIVO\n'); ok('HPNAME aceita os padrões do EduCAD sem o prefixo EDU_',E("S.hatchPat.pname")=='EDU_CULTIVO')
