    reset(); run('TEXTSIZE 7\nTEXT 0,0  0 A\n\n'); e=ents()
    ok('TEXTSIZE define a altura padrão (Enter na altura)',e and near(e[0]['h'],7),e)
    reset(); run('POLYGON 6 0,0 I 10\nPOLYGON 4 50,0 C 10\nPOLYGON 5 A 100,0 110,0\n')
