    # ── ponto digitado = clique sobre o objeto; seleção por teclado
    reset(); run('RECTANG 0,0 100,50\nMOVE 0,25\n\n0,0 10,10\n')
    e=ents(); ok('MOVE: objeto escolhido por ponto digitado',near(e[0]['x'],10) and near(e[0]['y'],10),e)
    reset(); run('RECTANG 0,0 100,50\nCIRCLE 200,0 5\nCOPY L\n\n0,0 0,100\n\n')
    e=ents(); ok('Seleção L (último objeto)',tps()==['rect','circ','circ'] and near(e[2]['cy'],100),tps())
    run('MOVE P\n\n0,0 1000,0\n'); e=ents(); ok('Seleção P (anterior)',near(e[1]['cx'],1200),e[1])
    reset(); run('RECTANG 0,0 10,10\nRECTANG 20,0 30,10\nCIRCLE 100,100 5\nERASE J -5,-5 35,15\n\n')
    ok('Seleção J (janela) por teclado',tps()==['circ'],tps())
    reset(); run('RECTANG 0,0 10,10\nRECTANG 20,0 30,10\nERASE C 25,5 5,-5\n\n')
    ok('Seleção C (cruzando) por teclado',tps()==[],tps())
    reset(); run('RECTANG 0,0 100,50\nOFFSET 5 50,0 50,-20\n\n')
    e=ents(); ok('OFFSET: objeto e lado por pontos digitados',len(e)==2 and near(e[1]['w'],110),e[1:] )
